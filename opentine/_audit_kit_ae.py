"""The kit's README and its artifact-evaluation package, ``ae/`` (0.49).

``ae/`` follows the shape ACM artifact-evaluation committees ask for: a README
that states which badges the artifact claims (Available, Functional,
Reproduced), what each claim rests on, the requirements, and the exact
commands, plus scripts that run them. ``ae/verify_kit.py`` needs only the
Python standard library: it checks ``SHA256SUMS`` and runs the kit's own
``tine-verify.pyz`` (which refuses the network itself) over ``evidence/``.
``ae/reproduce.sh`` needs opentine and re-derives the replay verdict. The
badge claims are the authors' to make; the README says so.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

VERIFY_KIT = '''"""Check this audit kit with the Python standard library alone (no network)."""
import hashlib
import subprocess
import sys
from pathlib import Path

KIT = Path(__file__).resolve().parent.parent


def sums_ok() -> bool:
    ok = True
    listed = set()
    for line in (KIT / "SHA256SUMS").read_text(encoding="utf-8").splitlines():
        digest, _, name = line.partition("  ")
        listed.add(name)
        path = KIT / name
        if not path.is_file() or hashlib.sha256(path.read_bytes()).hexdigest() != digest:
            print(f"FAIL {name}")
            ok = False
    found = {p.relative_to(KIT).as_posix() for p in KIT.rglob("*") if p.is_file()}
    for extra in sorted(found - listed - {"SHA256SUMS"}):
        print(f"FAIL {extra}: not listed in SHA256SUMS")
        ok = False
    return ok


def main() -> int:
    ok = sums_ok()
    print("SHA256SUMS", "pass" if ok else "fail")
    command = [sys.executable, "-I", "-S", str(KIT / "tine-verify.pyz"), str(KIT / "evidence")]
    key = KIT / "evidence" / "trust" / "pubkey.pub"
    if key.is_file():
        command += ["--pubkey", str(key)]
    done = subprocess.run(command, capture_output=True, text=True, check=False)
    print(done.stdout.strip())
    print("tine-verify.pyz", "pass" if done.returncode == 0 else "fail")
    ok = ok and done.returncode == 0
    print("PASS" if ok else "FAIL")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
'''

VERIFY_SH = '#!/bin/sh\n# Functional badge: verify the kit offline.\nset -eu\ncd "$(dirname "$0")/.."\nexec python3 -I ae/verify_kit.py\n'  # noqa: E501
VERIFY_PS1 = "# Functional badge: verify the kit offline (Windows).\n$ErrorActionPreference = 'Stop'\nSet-Location (Join-Path $PSScriptRoot '..')\npython -I ae\\verify_kit.py\nexit $LASTEXITCODE\n"  # noqa: E501


def reproduce_sh(summary: dict[str, Any]) -> str:
    lines = ["#!/bin/sh", "# Reproduced badge: needs opentine (pip install opentine).", "set -eu",
             'cd "$(dirname "$0")/.."', "tine audit-kit verify ."]  # fmt: skip
    lines += [f"tine replay evidence/{r['file']} --verify" for r in summary["runs"]]
    return "\n".join(lines) + "\n"


def ae_readme(summary: dict[str, Any]) -> str:
    runs = "\n".join(f"- `{r['run_id']}`: `evidence/{r['file']}`, {r['digest']}"
                     for r in summary["runs"])  # fmt: skip
    replay = next((c for c in summary["checks"] if c["name"] == "replay"), None)
    replay_line = replay["detail"] if replay else "no replay attestation"
    return f"""# Artifact evaluation

This package was generated by `tine audit-kit build` (tine {summary["tine_version"]}) from
{summary["source"]["kind"]} `{summary["source"]["name"]}`. The badges below are the ACM
artifact-evaluation badges the authors may claim; the evaluators award them.

## Artifacts

{runs}

## Badges claimed

| Badge | What it rests on | How to check |
| --- | --- | --- |
| Artifacts Available | every file is pinned in `SHA256SUMS`; deposit the zip with a DOI |\
 `sha256sum -c SHA256SUMS` |
| Artifacts Evaluated: Functional | each run verifies offline with the bundled verifier |\
 `sh ae/verify.sh` or `ae\\verify.ps1` |
| Results Reproduced | {replay_line} | `sh ae/reproduce.sh` (needs opentine) |

## Requirements

- Functional: Python 3.11 or later, standard library only; no network. Any OS.
- Reproduced: `pip install opentine` at version {summary["tine_version"]} or later.
- Time: under a minute for either script on a laptop.

## Steps

1. `python3 -I ae/verify_kit.py`: checks `SHA256SUMS`, then runs
   `tine-verify.pyz` over `evidence/` (it refuses every network call itself).
2. Open `verify.html` in any browser, offline: it re-checks each run with the
   TypeScript verifier it carries.
3. `sh ae/reproduce.sh`: re-runs every kit check and re-derives the replay verdict.

Expected result: each step prints or shows PASS. `REPORT.md` is the verdict
recorded when the kit was built.
"""


def kit_readme(summary: dict[str, Any]) -> str:
    return f"""# Audit kit

Self-contained and air-gapped: nothing in this directory needs the network.
Built by tine {summary["tine_version"]} from {summary["source"]["kind"]}
`{summary["source"]["name"]}`.

| Path | What it is |
| --- | --- |
| `REPORT.md`, `report.html` | the verification report recorded at build time |
| `tine-verify.pyz` | the stdlib-only Python verifier (`python -I -S tine-verify.pyz evidence`) |
| `verify.html` | the TypeScript verifier as one offline page, with the runs embedded |
| `evidence/` | `tine evidence export --with-verifier`: runs, verify report, custody, trust |
| `crate/` | the Provenance Run Crate of each run (RO-Crate, Workflow Run Crate 0.5) |
| `attestations/` | the in-toto `replay/v1` attestation and its signer key, when present |
| `trust/witnesses.json` | the pinned witness set and log keys |
| `reports/` | each run's deterministic evidence page |
| `ae/` | the artifact-evaluation package (README and scripts) |
| `kit.json` | the build summary (`tine-cli-audit-kit-build-1`) |
| `SHA256SUMS` | every file above, by SHA-256 |

To check everything with opentine installed: `tine audit-kit verify .` (offline).
Without opentine: `python3 -I ae/verify_kit.py`, then open `verify.html`.
"""


def write_ae(out: Path, summary: dict[str, Any]) -> None:
    ae = out / "ae"
    ae.mkdir()
    texts = {
        "README.md": ae_readme(summary),
        "verify_kit.py": VERIFY_KIT,
        "verify.sh": VERIFY_SH,
        "verify.ps1": VERIFY_PS1,
        "reproduce.sh": reproduce_sh(summary),
    }
    for name, text in texts.items():
        (ae / name).write_bytes(text.encode("utf-8"))
    (out / "README.md").write_bytes(kit_readme(summary).encode("utf-8"))


__all__ = ["VERIFY_KIT", "ae_readme", "kit_readme", "write_ae"]
