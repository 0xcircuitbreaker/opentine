"""Cross-version backwards-compatibility gate: a newer opentine MUST read data
written by any release >= 0.3.0.

From v0.3.0 on, stored data is a compatibility contract. The fixtures under
``tests/fixtures/compat/vX_Y_Z/`` were produced by the REAL published
``opentine==X.Y.Z`` (installed from PyPI, not this tree) by
``scripts/gen_compat_fixtures.py`` and committed as golden inputs. This test
proves the CURRENT build still reads every one of them cleanly:

  * every ``.tine`` artifact loads and its integrity digest still verifies;
  * a signed artifact still verifies under the same key, in both stored
    signature shapes (full key_id/signer/signed_at, and bare);
  * the fork each release created loads and is never falsely rejected — for a
    pre-0.4.0 fork (id derived the old ``(parent, point)`` way, no recorded
    ``metadata.fork``) ``verify_fork_id`` must abstain, and for a 0.4.0+ fork,
    which records the fork act, it must confirm;
  * that release's v3 repository opens and ``load_run`` / ``fsck`` / ``search``
    / ``log`` all work, and the run reconstructs to the same content.

This is a permanent release gate. Each future release must add a sibling
``tests/fixtures/compat/vX_Y_Z/`` generated by that published release (see
``scripts/gen_compat_fixtures.py``) and one ``Golden`` row below, so a newer
opentine is always exercised against every stored-data shape it promises to
keep reading. Fixtures are never regenerated for an old release: their bytes
are the evidence.
"""

