// Bundles the TS verifier (ts/verifier/src/browser/entry.ts) into the
// committed opentine/data/ui/tine-verifier.js that `tine ui` serves to its Web
// Worker. `node:crypto`, `node:zlib` and `node:fs` resolve to the browser
// stand-ins in ts/verifier/src/browser/, and `Buffer` to its slice of Node's.
// Pinned esbuild, fixed working directory and no timestamps: the same inputs
// give the same bytes on every machine (CI rebuilds and diffs the copy).
// Needs `npm ci` in ts/verifier first (the @noble packages live there).

import { build } from "esbuild";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const browser = join(here, "..", "verifier", "src", "browser");
const outfile = process.argv[2] ?? join(here, "..", "..", "opentine", "data", "ui", "tine-verifier.js");

await build({
  absWorkingDir: here,
  entryPoints: [join(browser, "entry.ts")],
  outfile,
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2020",
  minify: true,
  legalComments: "eof",
  charset: "utf8",
  alias: {
    "node:crypto": join(browser, "crypto.ts"),
    "node:zlib": join(browser, "zlib.ts"),
    "node:fs": join(browser, "fs.ts"),
  },
  inject: [join(browser, "buffer.ts")],
  banner: { js: "// tine-verifier.js: generated by ts/run-viewer/build-verifier.mjs from ts/verifier. Do not edit." },
  logLevel: "warning",
});
